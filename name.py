name="ada loveloce"
# Метод title() преобразует первый символ каждого слова в строке к верхнему 
# регистру
print(name.title())
# Метод upper() преобразует все символы каждого слова в строке к верхнему 
# регистру
print(name.upper())
# Метод lower() преобразует все символы каждого слова в строке к нижнему 
# регистру
print(name.lower())
