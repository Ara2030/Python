first_name = "ada"
last_name = "lovelace"
# Чтобы вставить значение переменной в строку, поставьте букву f непосредственно перед открывающей кавычкой.Заключите имя (или имена) переменных, которые должны использоваться внутри строки, в фигурные скобки. такие строки называются f-строками.
full_name = f"{first_name} {last_name}"
print(full_name)
message = (f"Hello, {full_name.title()}!")
print(message)
