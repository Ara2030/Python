# C помощью функции range() можно легко вывести серию чисел. 
for value in range(1, 5):
    print(value)
# Python начинает отсчет от первого переданного 
# значения 1 и прекращает его при достижении 5.

# Чтобы вывести числа от 1 до 5, используйте вызов range(1, 6).

# range(6)  Выведет числа от 0 до 5